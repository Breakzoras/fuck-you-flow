export type Strings = typeof el;
export const STRINGS: Record<string, Strings> = { el, en };

/// Some keys are chosen by the backend at runtime (a model's note, for
/// instance), so they arrive as a plain string. Unknown keys come back
/// unchanged rather than blank, which makes a missing translation visible.
export function tk(lang: string, key: string, vars?: Record<string, string | number>): string {
  return t(lang, key as keyof Strings, vars);
}

export function t(lang: string, key: keyof Strings, vars?: Record<string, string | number>): string {
  let s = (STRINGS[lang] ?? el)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
